// Package render writes every AI assistant's copy of a project's instructions, skills, commands
// and subagents from one source: the base wf owns in .agents/base, and the project's own part in
// .agents/project, which wins where the two disagree.
package render

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"text/template"

	"go.yaml.in/yaml/v3"
)

// The files and directories of a project that wf reads and writes, relative to its root.
const (
	ConfigFile = ".wf.yml"
	LockFile   = ".wf.lock"
	BaseDir    = ".agents/base"
	ProjectDir = ".agents/project"
)

// NotFoundError is something the caller named that is not there: their mistake, not wf's.
type NotFoundError struct{ message string }

func (err *NotFoundError) Error() string { return err.message }

// NotFound returns a NotFoundError saying message.
func NotFound(message string) error { return &NotFoundError{message} }

// File is one generated file: its slash-separated path from the project root, and its content.
type File struct {
	Path string
	Data []byte
}

type kind int

const (
	instructions kind = iota
	// workflowFile is a file of .workflow/: the guide and the templates specs and records start from.
	workflowFile
	skill
	command
	subagent
)

// source is one thing wf generates from, with its base part, its project part, or both.
type source struct {
	kind    kind
	name    string
	base    *document
	project *document
	// baseText is the base part as rendered, for wf show --base.
	baseText []byte
}

// Render returns every file wf sync writes for the project at dir, sorted by path. version is the
// wf version named in each file's header.
func Render(dir, version string) ([]File, error) {
	sources, err := load(dir)
	if err != nil {
		return nil, err
	}
	header := header(version)

	var files []File
	for _, src := range sources {
		generated, err := src.files(header)
		if err != nil {
			return nil, err
		}
		files = append(files, generated...)
	}
	slices.SortFunc(files, func(a, b File) int { return strings.Compare(a.Path, b.Path) })
	return files, nil
}

// Skill returns the skill name as an assistant reads it or, with baseOnly, its base as rendered.
func Skill(dir, version, name string, baseOnly bool) ([]byte, error) {
	sources, err := load(dir)
	if err != nil {
		return nil, err
	}
	index := slices.IndexFunc(sources, func(src source) bool { return src.kind == skill && src.name == name })
	if index < 0 {
		return nil, &NotFoundError{fmt.Sprintf("no skill %q in %s or %s", name, BaseDir, ProjectDir)}
	}
	src := sources[index]
	if baseOnly {
		if src.base == nil {
			return nil, &NotFoundError{fmt.Sprintf("skill %q has no base: it is the project's own", name)}
		}
		return src.baseText, nil
	}
	files, err := src.files(header(version))
	if err != nil {
		return nil, err
	}
	return files[0].Data, nil
}

// header opens every generated file, after its frontmatter.
func header(version string) string {
	return fmt.Sprintf("<!-- Generated by wf %s from %s and %s. Do not edit. -->", version, BaseDir, ProjectDir)
}

// load reads .wf.yml and both parts of every source, rendering the base parts as templates.
func load(dir string) ([]source, error) {
	data, err := readConfig(dir)
	if err != nil {
		return nil, err
	}

	var sources []source
	find := func(k kind, name string) *source {
		index := slices.IndexFunc(sources, func(src source) bool { return src.kind == k && src.name == name })
		if index < 0 {
			sources = append(sources, source{kind: k, name: name})
			index = len(sources) - 1
		}
		return &sources[index]
	}

	for _, part := range []string{BaseDir, ProjectDir} {
		err := walk(filepath.Join(dir, filepath.FromSlash(part)), func(rel string, content []byte) error {
			where := part + "/" + rel
			k, name, ok := classify(rel)
			if !ok {
				return fmt.Errorf("%s: wf does not know this file; see the layout in wf's README", where)
			}
			// A template is copied whole into each new spec or record, so a project part added under
			// it would land in every one of them.
			if part == ProjectDir && k == workflowFile && name != "GUIDE" {
				return &NotFoundError{fmt.Sprintf("%s: a template takes no project part; say what the project needs in %s/skills/domain-specs/SKILL.md", where, ProjectDir)}
			}
			if part == BaseDir {
				if content, err = renderTemplate(where, content, data); err != nil {
					return err
				}
			}
			doc, err := parseDocument(where, content)
			if err != nil {
				return err
			}
			src := find(k, name)
			if part == BaseDir {
				src.base, src.baseText = &doc, content
			} else {
				src.project = &doc
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	return sources, nil
}

// workflowFiles are the files at the top of .agents/base and .agents/project that become
// .workflow/<name>.
var workflowFiles = []string{"GUIDE.md", "SPEC-TEMPLATE.md", "DECISION-TEMPLATE.md"}

// classify says what a file under .agents/base or .agents/project is, from its path there.
func classify(rel string) (k kind, name string, ok bool) {
	parts := strings.Split(rel, "/")
	switch {
	case rel == "AGENTS.md":
		return instructions, "AGENTS", true
	case slices.Contains(workflowFiles, rel):
		return workflowFile, strings.TrimSuffix(rel, ".md"), true
	case len(parts) == 3 && parts[0] == "skills" && parts[2] == "SKILL.md":
		return skill, parts[1], true
	case len(parts) == 2 && parts[0] == "commands" && path.Ext(parts[1]) == ".md":
		return command, strings.TrimSuffix(parts[1], ".md"), true
	case len(parts) == 2 && parts[0] == "subagents" && path.Ext(parts[1]) == ".md":
		return subagent, strings.TrimSuffix(parts[1], ".md"), true
	}
	return 0, "", false
}

// walk calls visit with the slash-separated path and content of every file under root. A missing
// root has no files. Names starting with a dot, like .DS_Store, are skipped.
func walk(root string, visit func(rel string, content []byte) error) error {
	err := filepath.WalkDir(root, func(full string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if strings.HasPrefix(entry.Name(), ".") && full != root {
			if entry.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if entry.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(root, full)
		if err != nil {
			return err
		}
		content, err := ReadText(full)
		if err != nil {
			return err
		}
		return visit(filepath.ToSlash(rel), content)
	})
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	return err
}

// ReadText reads a text file as wf compares and renders it: Windows line endings become \n and a
// byte order mark is dropped, so a checkout with core.autocrlf, or a file saved by a Windows
// editor, reads the same as any other.
func ReadText(file string) ([]byte, error) {
	content, err := os.ReadFile(file)
	content = bytes.TrimPrefix(content, []byte("\xef\xbb\xbf"))
	return bytes.ReplaceAll(content, []byte("\r\n"), []byte("\n")), err
}

func readConfig(dir string) (map[string]any, error) {
	content, err := ReadText(filepath.Join(dir, ConfigFile))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, &NotFoundError{fmt.Sprintf("no %s in %s: run wf in the project's root", ConfigFile, dir)}
	}
	if err != nil {
		return nil, err
	}
	data := map[string]any{}
	if err := yaml.Unmarshal(content, &data); err != nil {
		return nil, fmt.Errorf("reading %s: %w", ConfigFile, err)
	}
	return data, nil
}

// renderTemplate renders a base file with .wf.yml as its data. The delimiters are [[ ]] because
// skills hold literal {{ }}, such as Vue's interpolation.
func renderTemplate(name string, content []byte, data map[string]any) ([]byte, error) {
	tmpl, err := template.New(name).Delims("[[", "]]").Option("missingkey=error").Parse(string(content))
	if err != nil {
		return nil, fmt.Errorf("reading template: %w", err)
	}
	var out bytes.Buffer
	if err := tmpl.Execute(&out, data); err != nil {
		// A key the base uses and .wf.yml lacks is the project's to add, not a fault in wf.
		if match := missingKey.FindStringSubmatch(err.Error()); match != nil && strings.HasPrefix(name, BaseDir+"/") {
			return nil, &NotFoundError{fmt.Sprintf("%s uses %s, which %s does not set; add %s: to it", name, match[1], ConfigFile, match[1])}
		}
		return nil, fmt.Errorf("rendering template: %w", err)
	}
	return out.Bytes(), nil
}

// missingKey finds the key in text/template's error for a map with no entry for it.
var missingKey = regexp.MustCompile(`map has no entry for key "([^"]+)"`)
